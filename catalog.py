def as_plugins():
    """展开成网关使用的插件结构。全部是 prompt 类型，开箱可用。"""
    out = []
    for cat, label, rows in GROUPS:
        for pid, name, desc, prompt in rows:
            out.append({
                "id": pid,
                "name": name,
                "desc": desc,
                "cat": cat,
                "catLabel": label,
                "kind": "prompt",
                "ready": True,
                "prompt": prompt,
            })
    return out


if __name__ == "__main__":
    ps = as_plugins()
    from collections import Counter
    print("总数:", len(ps))
    for k, v in Counter(p["catLabel"] for p in ps).items():
        print(f"  {k}: {v}")
